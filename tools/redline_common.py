"""Shared paths/helpers for the redline YOLO tooling.

The runtime reads ``models/redline_seg.pt`` (or ``.onnx``). Training uses the
dataset under ``datasets/redline``. This module keeps those paths in one place
so the split/train/eval/setup scripts cannot drift apart.

``ensure_dataset_yaml()`` writes a *local* YAML with an absolute dataset root.
Ultralytics resolves relative ``path:`` values inconsistently across versions
and working directories, so the training scripts always use this generated file.
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / "datasets" / "redline"
MODELS_DIR = ROOT / "models"

DEFAULT_MODEL_STEM = "redline_seg"
DEFAULT_BASE_MODEL = "yolov8n-seg.pt"

LOCAL_YAML = BASE / "redline.local.yaml"


def dataset_yaml_path() -> Path:
    """Path of the generated YAML with an absolute dataset root."""
    return LOCAL_YAML


def ensure_dataset_yaml() -> Path:
    """(Re)generate the local dataset YAML and return its path."""
    BASE.mkdir(parents=True, exist_ok=True)
    text = (
        "# Auto-generated by tools/redline_common.py. Do not edit.\n"
        f"path: {BASE.as_posix()}\n"
        "train: images/train\n"
        "val: images/val\n"
        "\n"
        "names:\n"
        "  0: base_area\n"
    )
    LOCAL_YAML.write_text(text, encoding="utf-8")
    return LOCAL_YAML


def model_candidates() -> list[Path]:
    """Trained redline model candidates, in preference order."""
    return [
        MODELS_DIR / f"{DEFAULT_MODEL_STEM}.pt",
        MODELS_DIR / f"{DEFAULT_MODEL_STEM}.onnx",
    ]


def find_trained_model() -> Path | None:
    for p in model_candidates():
        if p.exists():
            return p
    return None


def count_files(directory: Path, suffixes: tuple[str, ...]) -> int:
    if not directory.is_dir():
        return 0
    return sum(1 for p in directory.iterdir()
               if p.is_file() and p.suffix.lower() in suffixes)


def dataset_counts() -> dict[str, int]:
    return {
        "images/raw": count_files(BASE / "images" / "raw", (".png", ".jpg", ".jpeg", ".webp")),
        "labels/raw": count_files(BASE / "labels" / "raw", (".txt",)),
        "images/train": count_files(BASE / "images" / "train", (".png", ".jpg", ".jpeg", ".webp")),
        "labels/train": count_files(BASE / "labels" / "train", (".txt",)),
        "images/val": count_files(BASE / "images" / "val", (".png", ".jpg", ".jpeg", ".webp")),
        "labels/val": count_files(BASE / "labels" / "val", (".txt",)),
    }
